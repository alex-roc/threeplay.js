// Generates types/global.d.ts: one `declare global` entry per engine API key,
// so global mode (`add`, `box`, `onKeyPress`… on window) is typed in editors.
// It reads the keys from a real headless engine built from dist/, so the list
// can never drift from the code. Run after `vite build` (part of `pnpm build`).
import { writeFileSync } from "node:fs";

const { createEngine, defaultPlugins, globalKeys } = await import("../dist/threeplay.js");
const k = createEngine({ loop: "manual", renderer: "none", physics: false }, defaultPlugins);

const keys = globalKeys(k).sort();

const lines = keys.map((key) => `  const ${key}: Engine["${key}"];`);
const out = `// Generated by scripts/gen-global.mjs — do not edit.
// Types for threeplay's global mode. In a JS file:
//   /// <reference types="threeplay/global" />
import type { Engine } from "threeplay";

declare global {
  /** The engine context returned by threeplay(). */
  const k: Engine;
${lines.join("\n")}
}

export {};
`;
writeFileSync(new URL("../types/global.d.ts", import.meta.url), out);
k.quit();
console.log(`types/global.d.ts: ${keys.length} globals`);
